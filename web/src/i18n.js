export const LANGS = [
  { id: 'pt', label: 'Português', locale: 'pt-BR', quasar: ptBR },
  { id: 'en', label: 'English', locale: 'en-US', quasar: enUS }
]

// A per-browser preference: storage may be blocked, so the browser's language is the fallback.
const saved = (() => { try { return localStorage.getItem('ujobs-lang') } catch { return null } })()
export const lang = ref(messages[saved] ? saved : navigator.language?.toLowerCase().startsWith('pt') ? 'pt' : 'en')

export const has = key => key in messages[lang.value]
export const t = (key, params = {}) =>
  (messages[lang.value][key] ?? messages.pt[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '')
export const locale = () => LANGS.find(l => l.id === lang.value).locale

export function setLang (id) {
  const l = LANGS.find(x => x.id === id) || LANGS[0]
  lang.value = l.id
  Lang.set(l.quasar)
  document.documentElement.lang = l.locale
  try { localStorage.setItem('ujobs-lang', l.id) } catch {}
}
